"""
app.py
Streamlit app for interactive heart disease risk prediction.

Run with:
    streamlit run app/app.py
(run from the project root so the relative model paths resolve)
"""

import joblib
import numpy as np
import pandas as pd
import streamlit as st

st.set_page_config(page_title="Heart Disease Predictor", page_icon="❤️", layout="centered")

MODEL_PATH = "models/best_model.pkl"
SCALER_PATH = "models/scaler.pkl"
COLUMNS_PATH = "models/feature_columns.pkl"


@st.cache_resource
def load_artifacts():
    model = joblib.load(MODEL_PATH)
    scaler = joblib.load(SCALER_PATH)
    columns = joblib.load(COLUMNS_PATH)
    return model, scaler, columns


model, scaler, feature_columns = load_artifacts()

st.title("❤️ Heart Disease Risk Predictor")
st.write(
    "Enter the patient's clinical details below. This tool is for "
    "Educational Purposes only and is **not** a medical diagnosis."
)

with st.form("patient_form"):
    col1, col2 = st.columns(2)

    with col1:
        age = st.number_input("Age", min_value=1, max_value=120, value=50)
        sex = st.selectbox("Sex", options=[("Male", 1), ("Female", 0)], format_func=lambda x: x[0])[1]
        cp = st.selectbox(
            "Chest Pain Type",
            options=[
                ("Typical Angina", 0),
                ("Atypical Angina", 1),
                ("Non-anginal Pain", 2),
                ("Asymptomatic", 3),
            ],
            format_func=lambda x: x[0],
        )[1]
        trestbps = st.number_input("Resting Blood Pressure (mm Hg)", min_value=80, max_value=220, value=120)
        chol = st.number_input("Serum Cholesterol (mg/dl)", min_value=100, max_value=600, value=200)
        fbs = st.selectbox("Fasting Blood Sugar > 120 mg/dl?", options=[("No", 0), ("Yes", 1)], format_func=lambda x: x[0])[1]
        restecg = st.selectbox(
            "Resting ECG Result",
            options=[("Normal", 0), ("ST-T Abnormality", 1), ("LV Hypertrophy", 2)],
            format_func=lambda x: x[0],
        )[1]

    with col2:
        thalach = st.number_input("Max Heart Rate Achieved", min_value=60, max_value=220, value=150)
        exang = st.selectbox("Exercise-Induced Angina?", options=[("No", 0), ("Yes", 1)], format_func=lambda x: x[0])[1]
        oldpeak = st.number_input("ST Depression (oldpeak)", min_value=0.0, max_value=10.0, value=1.0, step=0.1)
        slope = st.selectbox(
            "Slope of Peak Exercise ST Segment",
            options=[("Upsloping", 0), ("Flat", 1), ("Downsloping", 2)],
            format_func=lambda x: x[0],
        )[1]
        ca = st.selectbox("Number of Major Vessels (0-3)", options=[0, 1, 2, 3])
        thal = st.selectbox(
            "Thalassemia",
            options=[("Normal", 1), ("Fixed Defect", 2), ("Reversible Defect", 3)],
            format_func=lambda x: x[0],
        )[1]

    submitted = st.form_submit_button("Predict")

if submitted:
    input_dict = {
        "age": age, "sex": sex, "cp": cp, "trestbps": trestbps, "chol": chol,
        "fbs": fbs, "restecg": restecg, "thalach": thalach, "exang": exang,
        "oldpeak": oldpeak, "slope": slope, "ca": ca, "thal": thal,
    }
    input_df = pd.DataFrame([input_dict])[feature_columns]
    input_scaled = scaler.transform(input_df)

    prediction = model.predict(input_scaled)[0]
    probability = model.predict_proba(input_scaled)[0][1]

    st.subheader("Result")
    if prediction == 1:
        st.error(f"⚠️ High risk of heart disease (probability: {probability:.1%})")
    else:
        st.success(f"✅ Low risk of heart disease (probability: {probability:.1%})")

    st.progress(min(int(probability * 100), 100))
    st.caption(
        "This prediction is generated by a machine learning model trained on the "
        "UCI Heart Disease dataset and should not replace professional medical advice."
    )
